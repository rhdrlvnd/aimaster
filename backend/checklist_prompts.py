"""Shared checklist writing rules for planning, writing, review and repair."""
WRITING_RULES = '''
[결과의 목적과 항목 단위]
운영 매뉴얼을 재작성하지 말고, 후임자가 무엇을 인수하고 확인해야 하는지 체크리스트를 작성한다.
한 항목은 독립적으로 인수 완료 여부를 판단할 수 있는 한 업무다. 권한 신청·환경 구성·테스트·PR·배포·복구를 한 항목으로 묶지 않는다.
분리 기준은 실제 업무 목적이 다른가이다. 동일 업무의 준비→승인→시험→실행→결과 확인→기록은 보통 한 항목으로 묶는다. 각 단계가 체크 가능하다는 이유만으로 별도 항목을 만들지 않는다.
예: 승인된 주문 재처리는 대상 확인·승인·테스트·실행·결과 확인을 한 항목으로 묶는다. 일일 점검의 상태 확인·건수 대사·오류 분류·보고도 하나의 점검 업무다. 배포와 복구는 목적이 달라 분리할 수 있다. 개별 컬럼·수치·문장·기록 단계마다 항목을 만들지 않는다.
단일 업무 영역의 여러 문서는 보통 15~25개 수준의 검토 가능한 업무로 정리하되, 이것은 할당량이 아니다. 실제 독립 업무가 더 적거나 많으면 근거에 따라 조정한다. 항목 수를 늘리기 위한 분리는 금지한다.
미처리 사건·정정 대기·외부 답변 대기처럼 다음 조치가 있는 미결 업무는 일반 대응 절차에 묻지 말고 별도 항목으로 둔다.
특정 부서를 전제하지 않는다. 인사·재무·법무·개발 모두 문서에 있는 실제 업무에 적용한다.

[제목과 설명]
제목은 보통 10~25자, 최대 50자로 '접근 권한 확인', '배포 후 결과 확인'처럼 목적과 행동을 간단히 쓴다.
제목에 여러 작업을 ·와 쉼표로 나열하지 않는다. 전체 업무 목록에 맞는 제목을 먼저 설계한다.
description은 보통 150~300자, 최대 500자다. 아래 세 줄로 작성하고, 각 줄은 핵심 내용을 짧게 쓴다.
인수할 내용: 전달받을 업무·자료·현재 상태.
핵심 확인: 이 업무를 수행하는 데 필요한 핵심 조건·승인·예외.
완료 확인: 후임자가 무엇을 확인하거나 설명할 수 있으면 인수를 확인할 수 있는지.
완료 확인은 인수인계 확인 기준이며, 문서에 없는 새 운영 정책·기한·실행 의무를 만들지 않는다.
실제 운영 장애를 발생시키거나 운영 배포를 수행해야 인수가 완료된다는 식으로 쓰지 않는다.
필수 승인·안전 제한·핵심 시간 조건·현행/미적용 상태는 해당 업무에 보존한다. 세부 컬럼 길이, 모든 테스트 입력, 모든 기록 필드, 과거 실행 건수는 설명에 복사하지 말고 연결 근거에서 확인하게 한다.
글자 수를 맞추려고 핵심 조건을 삭제하지 않는다. 한도 안에 담을 수 없으면 독립적인 업무로 나눈다.
다른 항목의 긴 제목을 인용하거나 '다른 항목에서 관리하므로 여기서 반복하지 않는다' 같은 편집 설명을 쓰지 않는다.
공통 주의사항은 관련 업무에 필요한 만큼만 남긴다. 동일한 문장을 여러 항목에 반복하지 않는다.

[근거와 사실]
핵심 주장을 직접 뒷받침하는 근거를 보통 2~4개 선택하고 중복 근거는 제거한다. 단일 근거만 필요한 업무는 1개로 충분하다.
text 원문 인용은 짧지만 의미가 완결되는 연속 구절을 그대로 복사한다. 말줄임표로 합치거나 단어를 바꾸지 않는다. 필요한 근거를 개수에 맞추려고 삭제하지 않는다.
제안·미적용·보류와 현행을 구분한다. 미정인 일정·담당자·정책을 만들지 않는다.
text 근거의 slide는 null, visual 근거의 slide는 원문 청크의 실제 장표 번호다. visual의 quote는 장표에서 읽힌 내용을 근거로 한 설명이며, 문구의 완전 일치를 요구하지 않는다. 장표에 없는 주장은 금지한다.

[작성 방식 예시 — 아래 내용은 형식 예시이며 입력 문서에 없으면 생성하지 않는다]
나쁜 제목: 개발·운영 권한 신청과 환경·인증정보 설정 및 테스트 실행 관리
나누는 방식: 접근 권한 확인 / 개발환경 구성과 시험 실행 / 인증정보 취급 기준 확인
좋은 설명 예시:
인수할 내용: 테스트 환경 구성과 실행 방법을 전달받는다.
핵심 확인: 연결 대상과 예약 실행 설정을 확인한 뒤 문서의 시험 절차를 따른다.
완료 확인: 후임자가 시험 결과의 확인 위치와 실패 시 문의 대상을 설명할 수 있다.
'''

REVIEW_RULES = '''
[검토의 기준]
권장 분량·문장 개수·표현 취향만으로 재작성을 요구하지 않는다. 최대 글자 수는 프로그램이 검사한다. 세 줄 구조의 실제 이해 가능성과 내용 정확성을 검토한다.
체크리스트가 원문 전체를 다시 서술할 필요는 없다. 세부 필드·모든 예시·기록 항목이 설명에 없다는 이유만으로 추가를 요구하지 마라.
연결된 근거에서 세부 절차를 확인할 수 있고 업무의 목적·핵심 조건·인수 확인 기준이 있으면 충분하다.
다만 실제 업무 자체의 누락, 잘못된 사실, 필수 승인/금지/중요 조건 누락, 현행과 미적용 혼동은 계속 지적한다.
완료 확인은 제안된 인수 확인 기준이다. 원문에 같은 문장이 없다는 이유로 지적하지 말고 새로운 운영 의무를 만들어내는지만 확인한다.
여러 다른 목적의 독립 업무가 합쳐져 있을 때만 분리를 제시한다. 같은 업무의 준비·승인·실행·검증·보고는 하위 절차이며 별개 업무 누락으로 지적하지 않는다. 원문에서 세부 절차를 확인할 수 있으면 모든 하위 절차를 설명에 쓰거나 각각 별도 카드로 만들 필요가 없다.
근거 수를 늘리거나 설명을 길게 만드는 것 자체를 품질 개선으로 보지 않는다.
중복을 지적할 때 다른 항목을 참조한다는 긴 문장을 추가하도록 요구하지 않는다.
'''


def validate_readability(items):
    for index,item in enumerate(items):
        if len(item.title)>50:
            raise ValueError(f'항목 {index+1}: 제목을 50자 이내의 한 업무로 줄이세요.')
        if len(item.description)>500:
            raise ValueError(f'항목 {index+1}: 설명은 500자 이내입니다. 세부 절차는 근거에 남기고 독립 업무는 나누세요.')
